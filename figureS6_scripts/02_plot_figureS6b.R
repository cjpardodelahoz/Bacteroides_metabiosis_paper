#!/usr/bin/env Rscript

# -----------------------------------------------------------------------------
# Figure S6B plotting script
#
# Purpose:
# Validate PICRUSt2 custom-trait predictions against paired shotgun
# metagenomes, sample by sample, for four features:
#   total digestive CAZymes, total secreted digestive CAZymes, and secreted
#   CAZymes targeting host glycan or pectin.
#
# Design notes:
# - PICRUSt2 side: predicted gene copies summed over the assessable ASVs
#   (NSTI <= 2) detected at >= 0.1% of the sample's 16S reads.
# - Metagenome side: number of distinct CGC genes carrying each feature in the
#   sample's assembly (data/figureS6/metagenome_sample_features.tsv).
# - Spearman correlation per feature; Holm adjustment across the four tests.
# - Both axes plotted as log10(x + 0.5).
#
# Inputs:
# - data/figure6/ PICRUSt2 inputs (generated by 00_generate_picrust_data.R)
# - data/figureS6/metagenome_sample_features.tsv
# - data/Liao_etal_2021/tblcounts_asv_wide.csv
#
# Outputs:
# - results/figureS6/FigS6B.pdf
# - results/figureS6/FigS6B_spearman.csv
# -----------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
})

source("figure6_scripts/helpers_picrust.R")

MIN_REL_ABUND <- 0.001
OFFSET <- 0.5

dir.create("results/figureS6", showWarnings = FALSE, recursive = TRUE)

# -----------------------------------------------------------------------------
# 1) Per-ASV predicted copies
# -----------------------------------------------------------------------------

message("Loading inputs...")
membership <- read_history_samples()
counts <- read_liao_asv_counts(membership$SampleID)
pred_secreted <- read_predictions("secreted")
pred_all <- read_predictions("all_digestive")
marker <- read_marker()

trait_cols <- setdiff(names(pred_secreted), "sequence")
stopifnot(setequal(trait_cols, setdiff(names(pred_all), "sequence")))
colmap <- make_substrate_colmap(trait_cols)

asv_features <- pred_secreted[, .(ASV = as.character(sequence), picrust_secreted = rowSums(.SD)),
                              .SDcols = trait_cols]
asv_features[, picrust_host_glycan := substrate_score(pred_secreted, colmap, "host glycan")]
asv_features[, picrust_pectin := substrate_score(pred_secreted, colmap, "pectin")]
asv_features <- merge(asv_features,
                      pred_all[, .(ASV = as.character(sequence), picrust_digestive = rowSums(.SD)),
                               .SDcols = trait_cols],
                      by = "ASV")
asv_features <- merge(asv_features, marker, by = "ASV", all.x = TRUE)

# -----------------------------------------------------------------------------
# 2) Per-sample summed predicted copies (ASVs >= 0.1% relative abundance)
# -----------------------------------------------------------------------------

message("Summing predicted copies per sample...")
picrust_cols <- c("picrust_digestive", "picrust_secreted", "picrust_host_glycan", "picrust_pectin")
totals <- counts[, .(total_reads = sum(Count)), by = SampleID]
x <- merge(counts, asv_features, by = "ASV")
x <- x[!is.na(copy16S) & !is.na(NSTI) & NSTI <= NSTI_MAX]
x <- merge(x, totals, by = "SampleID")
x[, rel := Count / total_reads]

picrust <- unique(x[, .(SampleID)])
picrust <- merge(picrust, x[rel >= MIN_REL_ABUND, lapply(.SD, sum), by = SampleID, .SDcols = picrust_cols],
                 by = "SampleID", all.x = TRUE)
for (col in picrust_cols) picrust[is.na(get(col)), (col) := 0]

# -----------------------------------------------------------------------------
# 3) Pair with metagenome gene counts and correlate
# -----------------------------------------------------------------------------

meta <- fread("data/figureS6/metagenome_sample_features.tsv", colClasses = c(SampleID = "character"))
manifest <- fread("data/read_metadata.csv", colClasses = c(SampleID = "character"))
stopifnot(!anyDuplicated(manifest$SampleID), !anyDuplicated(meta$SampleID),
          all(meta$SampleID %in% manifest$SampleID))
paired <- merge(picrust, meta, by = "SampleID")
message(sprintf("PICRUSt samples: %d | metagenome samples: %d | paired: %d",
                nrow(picrust), nrow(meta), nrow(paired)))

feature_map <- data.table(
  feature = c("Total digestive CAZymes", "Total digestive secreted CAZymes",
              "Secreted CAZymes targeting host glycan", "Secreted CAZymes targeting pectin"),
  picrust = picrust_cols,
  metagenome = c("n_digestive_genes", "n_secreted_genes", "n_host_glycan_genes", "n_pectin_genes")
)

spearman <- rbindlist(lapply(seq_len(nrow(feature_map)), function(i) {
  xv <- paired[[feature_map$picrust[i]]]
  yv <- paired[[feature_map$metagenome[i]]]
  ok <- is.finite(xv) & is.finite(yv)
  sp <- cor.test(xv[ok], yv[ok], method = "spearman", exact = FALSE)
  data.table(feature = feature_map$feature[i], n_samples = sum(ok),
             spearman_rho = unname(sp$estimate), p_value = sp$p.value)
}))
spearman[, p_holm := p.adjust(p_value, method = "holm")]
print(spearman, digits = 3)
fwrite(spearman, "results/figureS6/FigS6B_spearman.csv")

# -----------------------------------------------------------------------------
# 4) Plot
# -----------------------------------------------------------------------------

message("Generating FigS6B...")
tf <- function(v) log10(v + OFFSET)
d <- rbindlist(lapply(seq_len(nrow(feature_map)), function(i) {
  data.table(SampleID = paired$SampleID, feature = feature_map$feature[i],
             picrust = tf(paired[[feature_map$picrust[i]]]),
             metagenome = tf(paired[[feature_map$metagenome[i]]]))
}))
d[, feature := factor(feature, levels = feature_map$feature)]
# Square panels: each facet spans the same range on both axes.
lims <- d[, .(lo = min(picrust, metagenome), hi = max(picrust, metagenome)), by = feature]
corners <- rbind(lims[, .(feature, metagenome = lo, picrust = lo)],
                 lims[, .(feature, metagenome = hi, picrust = hi)])
ann <- spearman[, .(feature = factor(feature, levels = feature_map$feature),
                    label = sprintf("Spearman rho = %.2f\nn = %d", spearman_rho, n_samples))]

figs6b <- ggplot(d, aes(metagenome, picrust)) +
  geom_point(alpha = 0.35, size = 0.8, color = "#2F6B7C") +
  geom_smooth(method = "lm", formula = y ~ x, color = "#C25B3C", linewidth = 0.6) +
  geom_text(data = ann, aes(label = label), x = -Inf, y = Inf, hjust = -0.1, vjust = 1.2,
            size = 3, inherit.aes = FALSE) +
  geom_blank(data = corners, inherit.aes = TRUE) +
  facet_wrap(~feature, scales = "free", ncol = 2) +
  labs(x = "Metagenome gene copies, log10(copies + 0.5)",
       y = "PICRUSt2 predicted copies summed over ASVs >= 0.1%, log10(copies + 0.5)") +
  theme_bw(base_size = 10) +
  theme(aspect.ratio = 1)

ggsave("results/figureS6/FigS6B.pdf", figs6b, width = 8, height = 7.5)

message("Saved: results/figureS6/FigS6B.pdf")
message("Saved: results/figureS6/FigS6B_spearman.csv")
