#!/usr/bin/env Rscript

# -----------------------------------------------------------------------------
# Figure S6A plotting script
#
# Purpose:
# Compare PICRUSt2-predicted secreted CAZyme content per dbCAN substrate between
# Bacteroidaceae ASVs and all other residual (non-Pseudomonadota) ASVs, and plot
# effect size vs. typical copy number for Bacteroidaceae-enriched substrates.
#
# Design notes:
# - ASVs: assessable (NSTI <= 2), non-Pseudomonadota ASVs of the Figure 1E set.
# - Bacteroidaceae: ASVs assigned to genus Bacteroides (the only Bacteroidaceae
#   genus in this ASV set).
# - Per-ASV substrate score: predicted copies summed over the resolved Family_EC
#   trait columns that dbCAN maps to the substrate.
# - Two-sided Wilcoxon rank-sum test per substrate, BH-FDR across substrates;
#   enriched = q < 0.05.
#
# Inputs:
# - data/figure6/ PICRUSt2 inputs (generated by 00_generate_picrust_data.R)
#
# Outputs:
# - results/figureS6/FigS6A.pdf
# - results/figureS6/FigS6A_substrate_enrichment.csv
# -----------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
  library(ggrepel)
})

source("figure6_scripts/helpers_picrust.R")

FDR_CUTOFF <- 0.05

dir.create("results/figureS6", showWarnings = FALSE, recursive = TRUE)

# -----------------------------------------------------------------------------
# 1) Per-ASV substrate scores
# -----------------------------------------------------------------------------

message("Loading inputs...")
pred <- read_predictions("secreted")
marker <- read_marker()
taxonomy <- read_asv_taxonomy()

trait_cols <- setdiff(names(pred), "sequence")
colmap <- make_substrate_colmap(trait_cols)
substrates <- sort(unique(colmap$dbcan_substrate))

asv_features <- pred[, .(ASV = as.character(sequence))]
for (substrate in substrates) {
  asv_features[[substrate]] <- substrate_score(pred, colmap, substrate)
}
asv_features <- merge(asv_features, marker, by = "ASV", all.x = TRUE, sort = FALSE)
asv_features <- merge(asv_features, taxonomy[, .(ASV, is_bacteroidaceae = is_bacteroides, is_pseudo)],
                      by = "ASV", all.x = TRUE)
asv_features <- asv_features[is_pseudo == FALSE & !is.na(copy16S) & !is.na(NSTI) & NSTI <= NSTI_MAX]
message(sprintf("ASVs compared: %d Bacteroidaceae vs %d other | substrates: %d",
                asv_features[is_bacteroidaceae == TRUE, .N], asv_features[is_bacteroidaceae == FALSE, .N],
                length(substrates)))

# -----------------------------------------------------------------------------
# 2) Wilcoxon enrichment scan
# -----------------------------------------------------------------------------

enrichment <- rbindlist(lapply(substrates, function(substrate) {
  source_vals <- asv_features[is_bacteroidaceae == TRUE][[substrate]]
  other_vals <- asv_features[is_bacteroidaceae == FALSE][[substrate]]
  p <- tryCatch(wilcox.test(source_vals, other_vals, exact = FALSE)$p.value, error = function(e) NA_real_)
  data.table(substrate = substrate,
             n_bacteroidaceae = length(source_vals), n_other = length(other_vals),
             mean_bacteroidaceae = mean(source_vals), mean_other = mean(other_vals),
             median_bacteroidaceae = median(source_vals), median_other = median(other_vals),
             log2_mean_ratio = log2((mean(source_vals) + EPS) / (mean(other_vals) + EPS)),
             P = p)
}))
enrichment[, q := p.adjust(P, method = "BH")]
enrichment[, direction := fifelse(q < FDR_CUTOFF & log2_mean_ratio > 0, "Bacteroidaceae_enriched",
                                  fifelse(q < FDR_CUTOFF & log2_mean_ratio < 0, "Other_enriched",
                                          "not_FDR_significant"))]
setorder(enrichment, q, -log2_mean_ratio)
fwrite(enrichment, "results/figureS6/FigS6A_substrate_enrichment.csv")

# -----------------------------------------------------------------------------
# 3) Plot Bacteroidaceae-enriched substrates
# -----------------------------------------------------------------------------

plot_data <- enrichment[direction == "Bacteroidaceae_enriched"]
message(sprintf("Bacteroidaceae-enriched substrates plotted: %d", nrow(plot_data)))

figs6a <- ggplot(plot_data, aes(x = log2_mean_ratio, y = median_bacteroidaceae)) +
  geom_point(size = 2.5, color = "#3b6fa0") +
  geom_text_repel(aes(label = substrate), size = 3.2, max.overlaps = Inf, seed = 1) +
  labs(x = "log2 mean-ratio, Bacteroidaceae vs. other (raw Wilcoxon test)",
       y = "Median predicted enzyme copies per Bacteroidaceae ASV") +
  theme_bw(base_size = 12)

ggsave("results/figureS6/FigS6A.pdf", figs6a, width = 8, height = 6)

message("Saved: results/figureS6/FigS6A.pdf")
message("Saved: results/figureS6/FigS6A_substrate_enrichment.csv")
