#!/usr/bin/env Rscript

# -----------------------------------------------------------------------------
# Figure 6D plotting script
#
# Purpose:
# Fit the Figure 1E matched conditional-logistic models of Pseudomonadota
# expansion for five per-stool features and plot their standardized effects:
#   1. Bacteroides relative abundance (residual community benchmark)
#   2. Community-weighted mean (CWM) of all digestive CAZymes, all taxa
#   3. CWM of secreted digestive CAZymes, all taxa
#   4. CWM of secreted CAZymes targeting host glycan
#   5. CWM of secreted CAZymes targeting pectin
#
# Model (frozen Figure 1E design): per-history cumulative maximum of each
# log10 feature, outcome ~ feature + n_samples_interval + strata(set_id),
# Efron ties. Effects are log(OR) per SD of the feature.
#
# Inputs:
# - data/figure6/ PICRUSt2 inputs (generated by 00_generate_picrust_data.R)
# - data/Liao_etal_2021/tblcounts_asv_wide.csv
#
# Outputs:
# - results/figure6/Fig6D.pdf
# - results/figure6/Fig6D_model_results.csv
# -----------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(data.table)
  library(survival)
  library(ggplot2)
})

source("figure6_scripts/helpers_picrust.R")

dir.create("results/figure6", showWarnings = FALSE, recursive = TRUE)

# -----------------------------------------------------------------------------
# 1) Load inputs
# -----------------------------------------------------------------------------

message("Loading inputs...")
membership <- read_history_samples()
matched <- read_matched_sets()
counts <- read_liao_asv_counts(membership$SampleID)
taxonomy <- read_asv_taxonomy()
marker <- read_marker()
pred_secreted <- read_predictions("secreted")
pred_all <- read_predictions("all_digestive")

trait_cols <- setdiff(names(pred_secreted), "sequence")
stopifnot(setequal(trait_cols, setdiff(names(pred_all), "sequence")))

# -----------------------------------------------------------------------------
# 2) Per-ASV trait scores
# -----------------------------------------------------------------------------

message("Computing per-ASV trait scores...")
colmap <- make_substrate_colmap(trait_cols)

asv_features <- pred_secreted[, .(ASV = as.character(sequence),
                                  u_secreted = rowSums(.SD)), .SDcols = trait_cols]
asv_features[, u_host_glycan := substrate_score(pred_secreted, colmap, "host glycan")]
asv_features[, u_pectin := substrate_score(pred_secreted, colmap, "pectin")]
asv_features <- merge(
  asv_features,
  pred_all[, .(ASV = as.character(sequence), u_all_digestive = rowSums(.SD)), .SDcols = trait_cols],
  by = "ASV", all.x = TRUE
)
asv_features <- merge(asv_features, marker, by = "ASV", all.x = TRUE, sort = FALSE)
score_cols <- c("u_all_digestive", "u_secreted", "u_host_glycan", "u_pectin")

# -----------------------------------------------------------------------------
# 3) Per-stool features over the residual (non-Pseudomonadota) community
# -----------------------------------------------------------------------------

message("Building per-stool features...")
x <- merge(counts, taxonomy[, .(ASV, is_pseudo, is_bacteroides)], by = "ASV", sort = FALSE)
x <- merge(x[is_pseudo == FALSE], asv_features, by = "ASV", all.x = TRUE, sort = FALSE)
# Assessable: placed by PICRUSt2 with NSTI <= 2. CWM weights are 16S-copy-corrected.
x[, assessable := !is.na(copy16S) & !is.na(NSTI) & NSTI <= NSTI_MAX]
x[assessable == TRUE, a := Count / copy16S]
for (col in score_cols) x[is.na(get(col)), (col) := 0]

sample_features <- x[assessable == TRUE, .(
  bacteroides_log10   = log10(fifelse(sum(Count) > 0, sum(Count[is_bacteroides]) / sum(Count), 0) + EPS),
  cwm_all_digestive   = log10(sum(a * u_all_digestive) / sum(a) + EPS),
  cwm_secreted        = log10(sum(a * u_secreted) / sum(a) + EPS),
  cwm_host_glycan     = log10(sum(a * u_host_glycan) / sum(a) + EPS),
  cwm_pectin          = log10(sum(a * u_pectin) / sum(a) + EPS)
), by = SampleID]

feature_info <- data.table(
  x = 1:5,
  feature = c("bacteroides_log10", "cwm_all_digestive", "cwm_secreted", "cwm_host_glycan", "cwm_pectin"),
  description = c(
    "Bacteroides relative abundance",
    "CWM all digestive CAZymes, all taxa",
    "CWM secreted digestive CAZymes, all taxa",
    "CWM secreted CAZymes targeting host glycan",
    "CWM secreted CAZymes targeting pectin"
  ),
  label = c("Bact rel.\nabund.", "All taxa\n(all digestive\nCAZymes)",
            "All taxa\n(secreted digestive\nCAZymes)", "Host\nglycan", "Pectin")
)

md <- build_model_data(sample_features, feature_info$feature, membership, matched)
message(sprintf("Model rows: %d | matched sets: %d | patients: %d",
                nrow(md), uniqueN(md$set_id), uniqueN(md$PatientID)))

# -----------------------------------------------------------------------------
# 4) Fit one conditional-logistic model per feature
# -----------------------------------------------------------------------------

fit_feature <- function(feature) {
  fit <- clogit(as.formula(paste("outcome ~", feature, "+ n_samples_interval + strata(set_id)")),
                data = md, method = "efron", control = coxph.control(iter.max = 50))
  beta <- unname(coef(fit)[feature])
  se <- sqrt(vcov(fit)[feature, feature])
  sdv <- sd(md[[feature]])
  data.table(feature = feature,
             beta_per_SD = beta * sdv,
             lo_per_SD = (beta - 1.96 * se) * sdv,
             hi_per_SD = (beta + 1.96 * se) * sdv,
             OR_per_SD = exp(beta * sdv),
             OR_lo = exp((beta - 1.96 * se) * sdv),
             OR_hi = exp((beta + 1.96 * se) * sdv),
             P = 2 * pnorm(-abs(beta / se)),
             N = nrow(md), sets = uniqueN(md$set_id))
}

model_results <- merge(feature_info, rbindlist(lapply(feature_info$feature, fit_feature)),
                       by = "feature")[order(x)]
model_results[, P_BH := p.adjust(P, method = "BH")]
model_results[, significance := fifelse(P < 0.05, "significant", "non-significant")]
print(model_results[, .(description, OR_per_SD, OR_lo, OR_hi, P, P_BH, N, sets)], digits = 4)

fwrite(model_results[, .(feature, description, beta_per_SD, lo_per_SD, hi_per_SD,
                         OR_per_SD, OR_lo, OR_hi, P, P_BH, N, sets)],
       "results/figure6/Fig6D_model_results.csv")

# -----------------------------------------------------------------------------
# 5) Plot
# -----------------------------------------------------------------------------

message("Generating Fig6D...")
base_theme <- theme_minimal(base_size = 9) +
  theme(
    panel.grid.major.x = element_blank(),
    panel.grid.minor = element_blank(),
    panel.border = element_rect(color = "black", fill = NA, linewidth = 0.4),
    axis.title.x = element_blank(),
    axis.title.y = element_text(color = "black", size = 9),
    axis.text = element_text(color = "black", size = 8.5),
    axis.text.x = element_text(angle = 0, hjust = 0.5, vjust = 0.5, lineheight = 0.9),
    plot.margin = margin(8, 12, 8, 12)
  )

fig6d <- ggplot(model_results,
                aes(x = x, y = beta_per_SD, ymin = lo_per_SD, ymax = hi_per_SD, color = significance)) +
  geom_hline(yintercept = 0, linetype = "dashed", color = "gray50") +
  geom_pointrange(size = 0.3, linewidth = 0.4) +
  scale_color_manual(values = c(significant = "black", `non-significant` = "gray70"), guide = "none") +
  scale_x_continuous(breaks = model_results$x, labels = model_results$label, limits = c(0.4, 5.6)) +
  scale_y_continuous(breaks = seq(-0.4, 0.6, 0.2)) +
  coord_cartesian(ylim = c(-0.5, 0.65), clip = "off") +
  labs(y = "Effect on Pseudomonadota expansion\n(standardized log-odds per SD)") +
  base_theme

ggsave("results/figure6/Fig6D.pdf", fig6d, width = 5.2, height = 3.4)

message("Saved: results/figure6/Fig6D.pdf")
message("Saved: results/figure6/Fig6D_model_results.csv")
