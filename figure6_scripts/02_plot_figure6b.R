#!/usr/bin/env Rscript

# -----------------------------------------------------------------------------
# Figure 6B plotting script
#
# Purpose:
# Family-level CGC content: ladderized GTDB family tree with four aligned
# distribution panels (median and 95% range per MAG, by family):
#   1. digestive CGCs per genome (CGCs holding at least one GH/PL/CE gene)
#   2. digestive CGCs per genome holding at least one secreted digestive CAZyme
#   3. secreted digestive CAZymes annotated as host-glycan active (dbCAN-sub)
#   4. secreted digestive CAZymes annotated as pectin active (dbCAN-sub)
#
# Inputs:
# - data/figure6/cgc_data.csv (generated by 00_generate_cgc_data.R)
# - data/figure6/cgc_dbcansub_substrates.csv.gz (generated by 00_generate_cgc_data.R)
# - data/gtdb/bac120_taxonomy_r226.tsv
# - data/gtdb/bac120_r226.tree
#
# Outputs:
# - results/figure6/Fig6B.pdf
# - results/figure6/Fig6B_family_stats.csv
# -----------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
  library(patchwork)
  library(ggrepel)
  library(ape)
  library(ggtree)
})

if (!file.exists("data/figure6/cgc_data.csv") ||
    !file.exists("data/figure6/cgc_dbcansub_substrates.csv.gz")) {
  source("figure6_scripts/00_generate_cgc_data.R")
}
dir.create("results/figure6", showWarnings = FALSE, recursive = TRUE)

SEED <- 1
STRIP_FILLS <- c("gray82", "gray45")
BACTEROIDACEAE_TEAL <- "#4ae1d9"
PSEUDOMONADOTA_RED <- "#e15454"
LABEL_FAMILIES <- c("Bacteroidaceae", "Akkermansiaceae", "Tannerellaceae",
                    "Enterobacteriaceae", "Pseudomonadaceae")

split_ranks <- function(dt, col) {
  ranks <- c("domain", "phylum", "class", "order", "family", "genus", "species")
  parts <- tstrsplit(dt[[col]], ";", fixed = TRUE)
  for (i in seq_along(ranks)) {
    value <- if (i <= length(parts)) parts[[i]] else NA_character_
    dt[, (ranks[i]) := sub("^[a-z]__", "", value)]
  }
  # Prevotellaceae is split across placeholder families in GTDB taxonomy
  dt[grepl("revotella", genus), family := "Prevotellaceae"]
  invisible(dt)
}

# -----------------------------------------------------------------------------
# 1) Load CGC genes for quality-filtered MAGs
# -----------------------------------------------------------------------------

message("Loading CGC table...")
# cgc_data.csv only contains near-complete MAGs (completeness >= 90,
# contamination <= 10, contig N50 >= 50 kb). Family already harmonizes
# Prevotella-like genera to Prevotellaceae.
cgc <- fread("data/figure6/cgc_data.csv",
             select = c("Mag", "Cgc#", "Gene type", "Protein id", "Gene annotation",
                        "Family", "Has signalp gene"),
             col.names = c("mag", "cgc_id", "gene_type", "protein_id", "annotation",
                           "family", "secreted"))
quality <- unique(cgc[, .(mag, family)])[!is.na(family) & family != "" & family != "UBA932"]
cgc <- cgc[mag %chin% quality$mag]
message(sprintf("Quality-filtered MAGs: %d across %d families", nrow(quality), uniqueN(quality$family)))

# -----------------------------------------------------------------------------
# 2) Digestive (GH/PL/CE) CAZyme genes inside CGCs
# -----------------------------------------------------------------------------

# Drop any CGC containing a glycosyltransferase.
gt_cgcs <- unique(cgc[grepl("GT", annotation, fixed = TRUE), .(mag, cgc_id)])
cgc <- cgc[!gt_cgcs, on = .(mag, cgc_id)]
caz <- cgc[gene_type == "CAZyme"]

# Catalytic subfamily from the dbCAN annotation (handles fused annotations).
ann <- caz$annotation
subfam <- sub("^[^|]*\\|", "", ann)
n_pipe <- lengths(regmatches(ann, gregexpr("|", ann, fixed = TRUE)))
needs_scan <- which(n_pipe != 1L & grepl("GH|PL|CE", ann))
if (length(needs_scan)) {
  scanned <- vapply(strsplit(ann[needs_scan], "|", fixed = TRUE), function(fields) {
    hit <- fields[grepl("GH|PL|CE", fields)]
    if (!length(hit)) return(NA_character_)
    sub("\\+.*$", "", hit[1])
  }, character(1))
  subfam[needs_scan] <- fifelse(is.na(scanned), subfam[needs_scan], scanned)
}
caz[, cazy_subfam := subfam]
caz <- caz[grepl("GH|PL|CE", cazy_subfam)]
caz[, cazy_fam := sub("_.*$", "", cazy_subfam)]
message(sprintf("Digestive CAZyme genes in CGCs: %d across %d CGCs",
                nrow(caz), nrow(unique(caz[, .(mag, cgc_id)]))))

# -----------------------------------------------------------------------------
# 3) dbCAN-sub substrate annotations (host glycan / pectin)
# -----------------------------------------------------------------------------

message("Loading dbCAN-sub substrates...")
dbsub <- fread("data/figure6/cgc_dbcansub_substrates.csv.gz",
               col.names = c("mag", "protein_id", "subfam", "substrate"))
dbsub[, cazy_fam := sub("_.*$", "", subfam)]
dbsub[, host_glycan := grepl("(^|,[[:space:]]*)host glycan([[:space:]]*,|$)", substrate)]
dbsub[, pectin := grepl("(^|,[[:space:]]*)pectin([[:space:]]*,|$)", substrate)]
# Substrate hits only count when they belong to the gene's own CAZy family.
dbsub <- dbsub[host_glycan | pectin,
               .(host_glycan = any(host_glycan), pectin = any(pectin)),
               by = .(mag, protein_id, cazy_fam)]
caz <- merge(caz, dbsub, by = c("mag", "protein_id", "cazy_fam"), all.x = TRUE, sort = FALSE)
caz[is.na(host_glycan), host_glycan := FALSE]
caz[is.na(pectin), pectin := FALSE]

# -----------------------------------------------------------------------------
# 4) Per-genome counts
# -----------------------------------------------------------------------------

mag_counts <- caz[, .(
  n_digestive_cgcs          = uniqueN(cgc_id),
  n_digestive_cgcs_secreted = uniqueN(cgc_id[secreted]),
  n_secreted_hostglycan     = sum(secreted & host_glycan),
  n_secreted_pectin         = sum(secreted & pectin)
), by = mag]
mag_counts <- merge(mag_counts, quality, by = "mag")

# -----------------------------------------------------------------------------
# 5) Family tree from GTDB r226 (one random representative genome per family)
# -----------------------------------------------------------------------------

message("Building family tree...")
bac120_tree <- read.tree("data/gtdb/bac120_r226.tree")
bac120_tax <- fread("data/gtdb/bac120_taxonomy_r226.tsv", sep = "\t", header = FALSE,
                    col.names = c("genome", "classification"))
split_ranks(bac120_tax, "classification")

set.seed(SEED)
key <- bac120_tax[family %chin% unique(mag_counts$family) & genome %chin% bac120_tree$tip.label]
key <- key[, .SD[sample(.N, 1)], by = family][, .(genome, family, phylum)]

family_tree <- ladderize(keep.tip(bac120_tree, key$genome))
tree_plot <- ggtree(family_tree, ladderize = FALSE, size = 0.35)
tips <- as.data.table(tree_plot$data)[isTip == TRUE, .(genome = label, y)]
key <- merge(key, tips, by = "genome")
setorder(key, y)
n_tips <- nrow(key)
y_limits <- c(0.5, n_tips + 0.5)
message(sprintf("Families on the tree: %d", n_tips))

# -----------------------------------------------------------------------------
# 6) Family-level distributions (median and 95% range across MAGs)
# -----------------------------------------------------------------------------

stats <- merge(mag_counts, key[, .(family, y, phylum)], by = "family")
metrics <- c("n_digestive_cgcs", "n_digestive_cgcs_secreted", "n_secreted_hostglycan", "n_secreted_pectin")
long <- melt(stats, id.vars = c("family", "y", "phylum"), measure.vars = metrics,
             variable.name = "metric", value.name = "count")
fam_stats <- long[, .(
  n_mags = .N,
  median = as.numeric(median(count, na.rm = TRUE)),
  lo = as.numeric(quantile(count, 0.025, na.rm = TRUE)),
  hi = as.numeric(quantile(count, 0.975, na.rm = TRUE))
), by = .(family, y, phylum, metric)]

# -----------------------------------------------------------------------------
# 7) Panels
# -----------------------------------------------------------------------------

# Alternating phylum blocks in tip order
runs <- rle(key$phylum)
block_end <- cumsum(runs$lengths)
block_start <- block_end - runs$lengths + 1L
blocks <- data.table(
  phylum = runs$values,
  ymin = key$y[block_start] - 0.5,
  ymax = key$y[block_end] + 0.5,
  fill = STRIP_FILLS[seq_along(runs$values) %% 2L + 1L]
)
blocks[, ymid := (ymin + ymax) / 2]

make_strip <- function(with_labels = FALSE) {
  x_max <- if (with_labels) 12 else 1
  p <- ggplot(blocks) +
    geom_rect(aes(xmin = 0, xmax = 1, ymin = ymin, ymax = ymax, fill = fill)) +
    scale_fill_identity() +
    scale_x_continuous(limits = c(0, x_max), expand = c(0, 0)) +
    scale_y_continuous(limits = y_limits, expand = c(0, 0)) +
    theme_void()
  if (with_labels) {
    p <- p + ggrepel::geom_text_repel(
      aes(x = 1.2, y = ymid, label = phylum),
      hjust = 0, size = 2.6, fontface = "bold", direction = "y",
      nudge_x = 0.6, min.segment.length = 0, segment.size = 0.25,
      segment.colour = "gray40", box.padding = 0.08, seed = SEED
    )
  }
  p
}

make_panel <- function(metric_id, x_label, wrap_width = 20, label_families = FALSE) {
  d <- fam_stats[metric == metric_id]
  d[, dot_colour := fifelse(family == "Bacteroidaceae", BACTEROIDACEAE_TEAL,
                            fifelse(phylum == "Pseudomonadota", PSEUDOMONADOTA_RED, "black"))]
  d[, line_colour := fifelse(family == "Bacteroidaceae", BACTEROIDACEAE_TEAL,
                             fifelse(phylum == "Pseudomonadota", PSEUDOMONADOTA_RED, "gray55"))]
  x_max <- max(d$hi, na.rm = TRUE)

  p <- ggplot(d, aes(y = y)) +
    geom_linerange(aes(xmin = lo, xmax = hi, colour = line_colour), linewidth = 0.55) +
    geom_point(aes(x = median, colour = dot_colour), size = 0.9) +
    scale_colour_identity() +
    scale_x_continuous(expand = expansion(mult = c(0.06, 0.02))) +
    scale_y_continuous(limits = y_limits, expand = c(0, 0)) +
    labs(x = paste(strwrap(x_label, width = wrap_width), collapse = "\n"), y = NULL) +
    theme_minimal(base_size = 8) +
    theme(
      axis.text.y = element_blank(),
      axis.title.y = element_blank(),
      axis.text.x = element_text(colour = "black"),
      axis.title.x = element_text(colour = "black", margin = margin(t = 4)),
      panel.grid = element_blank(),
      panel.border = element_rect(colour = "black", fill = NA, linewidth = 0.5),
      plot.margin = margin(2, 2, 2, 2)
    )

  if (label_families) {
    lab <- d[family %chin% LABEL_FAMILIES]
    beside <- lab[family != "Bacteroidaceae"]
    # Bacteroidaceae reaches the right edge, so its label sits above the interval.
    above <- lab[family == "Bacteroidaceae"]
    p <- p +
      geom_text(data = beside, aes(x = hi + x_max * 0.03, label = family),
                hjust = 0, size = 2.3, fontface = "italic") +
      geom_segment(data = above, aes(x = hi, xend = hi, y = y + 0.35, yend = y + 1.2),
                   linewidth = 0.25, colour = "gray40") +
      geom_text(data = above, aes(x = hi, y = y + 1.7, label = family),
                hjust = 1, size = 2.3, fontface = "italic")
  }
  p
}

tree_panel <- tree_plot +
  scale_y_continuous(limits = y_limits, expand = c(0, 0)) +
  theme(plot.margin = margin(2, 0, 2, 2))

panels <- list(
  make_panel("n_digestive_cgcs", "Digestive CGCs"),
  make_panel("n_digestive_cgcs_secreted", "Digestive CGCs with secreted CAZymes"),
  make_panel("n_secreted_hostglycan", "Secreted CAZymes, host glycan"),
  make_panel("n_secreted_pectin", "Secreted CAZymes, pectin", label_families = TRUE)
)

fig6b <- wrap_plots(
  list(tree_panel, make_strip(), panels[[1]], make_strip(), panels[[2]],
       make_strip(), panels[[3]], make_strip(), panels[[4]], make_strip(TRUE)),
  nrow = 1,
  widths = c(1.1, 0.05, 0.75, 0.05, 0.75, 0.05, 0.75, 0.05, 0.75, 0.9)
)

height <- max(6, n_tips * 0.11)
ggsave("results/figure6/Fig6B.pdf", fig6b, width = 11, height = height, limitsize = FALSE)
fwrite(fam_stats[order(metric, -y)], "results/figure6/Fig6B_family_stats.csv")

message("Saved: results/figure6/Fig6B.pdf")
message("Saved: results/figure6/Fig6B_family_stats.csv")
