#!/usr/bin/env Rscript

# -----------------------------------------------------------------------------
# Figure 6C data-prep script
#
# Purpose:
# Build the sample-level family relative-abundance table used by Figure 6C.
#
# Design notes:
# - Patients with a single HCT only (the patient-day clinical universe used for
#   the manuscript analysis); day is relative to that transplant.
# - Quinolone prophylaxis start: first quinolone day within days [-10, 0].
# - Family relative abundances are computed from Liao et al. 2021 ASV counts,
#   summed by the `Family` column of data/figure6/asv_taxonomy.csv. The
#   denominator is the total ASV count of each sample.
# - Samples restricted to days [-10, 30] relative to HCT.
#
# Inputs:
# - data/Liao_etal_2021/tblhctmeta.csv
# - data/Liao_etal_2021/tbldrug.csv
# - data/Liao_etal_2021/tblASVsamples.csv
# - data/Liao_etal_2021/tblcounts_asv_wide.csv
# - data/figure6/asv_taxonomy.csv (generated by 00_generate_picrust_data.R)
#
# Output:
# - data/figure6/family_abundance.csv
# -----------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(data.table)
})

dir.create("data/figure6", showWarnings = FALSE, recursive = TRUE)

target_families <- c(
  "Bacteroidaceae",
  "Tannerellaceae",
  "Prevotellaceae",
  "Rikenellaceae",
  "Barnesiellaceae",
  "Marinifilaceae",
  "Dysgonomonadaceae",
  "Akkermansiaceae"
)

# -----------------------------------------------------------------------------
# 1) Single-HCT patients
# -----------------------------------------------------------------------------

message("Loading transplant metadata...")
tblhctmeta <- fread("data/Liao_etal_2021/tblhctmeta.csv", colClasses = c(PatientID = "character"))
hct <- tblhctmeta[, .(n_hct = .N, TimepointOfTransplant = TimepointOfTransplant[1]), by = PatientID][n_hct == 1]
message(sprintf("Patients with a single HCT: %d of %d", nrow(hct), uniqueN(tblhctmeta$PatientID)))

# -----------------------------------------------------------------------------
# 2) First quinolone prophylaxis day in [-10, 0]
# -----------------------------------------------------------------------------

message("Computing quinolone prophylaxis start...")
tbldrug <- fread("data/Liao_etal_2021/tbldrug.csv", colClasses = c(PatientID = "character"))
quin <- tbldrug[Category == "quinolones" & PatientID %chin% hct$PatientID]
# Expand each administration window to one row per day relative to HCT.
quin_days <- quin[, .(DayRelativeToNearestHCT = StartDayRelativeToNearestHCT:StopDayRelativeToNearestHCT),
                  by = .(PatientID, row_id = seq_len(nrow(quin)))]
first_quin_day <- quin_days[between(DayRelativeToNearestHCT, -10, 0),
                            .(first_quin_day = min(DayRelativeToNearestHCT)), by = PatientID]

# -----------------------------------------------------------------------------
# 3) Stool samples in days [-10, 30]
# -----------------------------------------------------------------------------

message("Preparing stool sample metadata...")
samples <- fread("data/Liao_etal_2021/tblASVsamples.csv",
                 select = c("SampleID", "PatientID", "Timepoint"),
                 colClasses = c(SampleID = "character", PatientID = "character"))
samples <- unique(samples, by = "SampleID")
samples <- merge(samples, hct[, .(PatientID, TimepointOfTransplant)], by = "PatientID")
samples[, DayRelativeToNearestHCT := Timepoint - TimepointOfTransplant]
samples <- samples[between(DayRelativeToNearestHCT, -10, 30)]

# -----------------------------------------------------------------------------
# 4) Family relative abundances from ASV counts
# -----------------------------------------------------------------------------

message("Computing family relative abundances from ASV counts...")
asv_family <- fread("data/figure6/asv_taxonomy.csv", select = c("ASV", "Family"))
count_header <- names(fread("data/Liao_etal_2021/tblcounts_asv_wide.csv", nrows = 0))
sample_ids <- intersect(samples$SampleID, count_header)
counts <- fread("data/Liao_etal_2021/tblcounts_asv_wide.csv", select = c("ASV", sample_ids))
counts <- melt(counts, id.vars = "ASV", variable.name = "SampleID", value.name = "Count",
               variable.factor = FALSE)[Count > 0]
counts <- merge(counts, asv_family, by = "ASV", all.x = TRUE)
totals <- counts[, .(total_count = sum(Count)), by = SampleID]
family_counts <- counts[Family %chin% target_families, .(Count = sum(Count)), by = .(SampleID, Family)]

family_abund <- CJ(SampleID = totals$SampleID, Family = target_families)
family_abund <- merge(family_abund, family_counts, by = c("SampleID", "Family"), all.x = TRUE)
family_abund[is.na(Count), Count := 0]
family_abund <- merge(family_abund, totals, by = "SampleID")
family_abund[, abund := Count / total_count]
family_abund <- dcast(family_abund, SampleID ~ paste0(Family, "_abund"), value.var = "abund")

# -----------------------------------------------------------------------------
# 5) Assemble and write
# -----------------------------------------------------------------------------

family_abundance <- merge(samples[, .(SampleID, PatientID, DayRelativeToNearestHCT)],
                          family_abund, by = "SampleID")
family_abundance <- merge(family_abundance, first_quin_day, by = "PatientID", all.x = TRUE)
setcolorder(family_abundance, c("SampleID", "PatientID", "DayRelativeToNearestHCT", "first_quin_day",
                                paste0(target_families, "_abund")))
setorder(family_abundance, PatientID, DayRelativeToNearestHCT, SampleID)

fwrite(family_abundance, "data/figure6/family_abundance.csv")
message(sprintf("Saved: data/figure6/family_abundance.csv (%d samples, %d patients)",
                nrow(family_abundance), uniqueN(family_abundance$PatientID)))
